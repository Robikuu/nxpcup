def parse(text):
    data = []
    for l in text.strip().split("\n"):
        m = re.match(r'L:(\d+)/(\d+) R:(-?\d+) F:(-?\d+) H:(-?\d+) TJ:(-?\d+) S:(-?\d+) LA:(\d+) ST:(\w+) VL:(\d+) VR:(\d+)', l.strip())
        if m:
            data.append({
                'raw_cte': int(m.group(3))/10.0, 'f_cte': int(m.group(4))/10.0,
                'h': int(m.group(5))/10.0, 'tj': int(m.group(6))/10.0,
                's': int(m.group(7))/10.0, 'la': int(m.group(8)),
                'st': m.group(9), 'vl': int(m.group(10)), 'vr': int(m.group(11))
            })
    return data

